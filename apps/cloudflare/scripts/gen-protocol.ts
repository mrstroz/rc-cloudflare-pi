/**
 * Compiles protocol/ for the Worker at build time (docs/spec/02 §10): Workers forbid code
 * generation from strings at runtime, so Ajv runs here and emits standalone validators.
 * Output goes to src/generated/ (gitignored); every script that reads it runs this first.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const PROTOCOL = new URL("../../../protocol/", import.meta.url);
const SCHEMAS = new URL("schemas/", PROTOCOL);
const OUT = new URL("../src/generated/", import.meta.url);

interface Hop {
  type: string;
  from: string;
  to: string;
  schema: string;
}

function readJson(url: URL): unknown {
  return JSON.parse(readFileSync(url, "utf8"));
}

/** `drive.client.schema.json` → `drive_client`. */
function exportName(schemaFile: string): string {
  return schemaFile.replace(/\.schema\.json$/, "").replaceAll(".", "_");
}

const schemaFiles = readdirSync(SCHEMAS)
  .filter((name) => name.endsWith(".schema.json"))
  .sort();
const messageSchemas = schemaFiles.filter((name) => name !== "common.schema.json");

const ajv = new Ajv2020({ strict: true, code: { source: true, esm: true } });
for (const file of schemaFiles) {
  ajv.addSchema(readJson(new URL(file, SCHEMAS)) as object);
}
const exports = Object.fromEntries(messageSchemas.map((file) => [exportName(file), file]));

const index = readJson(new URL("message-types.json", PROTOCOL)) as { hops: Hop[] };
const limits = readJson(new URL("limits.json", PROTOCOL));
const common = readJson(new URL("common.schema.json", SCHEMAS)) as {
  $defs: { error_reason: { enum: string[] } };
};

const hops = index.hops.map(({ type, from, to, schema }) => ({
  type,
  from,
  to,
  validator: exportName(schema),
}));

const protocolModule = `// Generated by scripts/gen-protocol.ts from protocol/. Do not edit.
import type { ValidateFunction } from "ajv";
import * as validators from "./validators.js";

export const ERROR_REASONS = ${JSON.stringify(common.$defs.error_reason.enum)} as const;
export type ProtocolErrorReason = (typeof ERROR_REASONS)[number];
export const LIMITS = ${JSON.stringify(limits)} as const;
export const HOPS = ${JSON.stringify(hops)} as const;
export const VALIDATORS: Record<(typeof HOPS)[number]["validator"], ValidateFunction> = validators;
`;

const declarations = messageSchemas
  .map((file) => `export declare const ${exportName(file)}: ValidateFunction;`)
  .join("\n");

mkdirSync(OUT, { recursive: true });
writeFileSync(new URL("validators.js", OUT), standaloneCode(ajv, exports));
writeFileSync(
  new URL("validators.d.ts", OUT),
  `// Generated by scripts/gen-protocol.ts. Do not edit.\nimport type { ValidateFunction } from "ajv";\n${declarations}\n`,
);
writeFileSync(new URL("protocol.ts", OUT), protocolModule);
